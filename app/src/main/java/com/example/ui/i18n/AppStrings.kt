    val languageDialog: LanguageDialogStrings,
    val themeDialog: ThemeDialogStrings,
    val common: CommonStrings
) {
    companion object {
        fun get(language: AppLanguage): AppStrings {
            return when (language) {
                AppLanguage.ES -> StringsEs
                AppLanguage.EN -> StringsEn
                AppLanguage.FR -> StringsFr
